// Helper functions
export const getFallbackChapterTransliteration = (chapterNo) => {
  return transliterationData[chapterNo] || null
}

export const getFallbackVerseTransliteration = (chapterNo, verseNo) => {
  const chapterData = transliterationData[chapterNo]
  if (!chapterData) return null

  const verse = chapterData.find((v) => v.verseNo === verseNo)
  return verse ? verse.translation : null
}

// Helper function to check if transliteration is available for a chapter
export const hasTransliterationData = (chapterNo) => {
  return !!transliterationData[chapterNo]
}

// Get all available chapters with transliteration
export const getAvailableTransliterationChapters = () => {
  return Object.keys(transliterationData)
    .map(Number)
    .sort((a, b) => a - b)
}

// Get total verses count for a chapter
export const getChapterVerseCount = (chapterNo) => {
  const chapterData = transliterationData[chapterNo]
  return chapterData ? chapterData.length : 0
}

// Get transliteration for a range of verses
export const getVerseRangeTransliteration = (chapterNo, startVerse, endVerse) => {
  const chapterData = transliterationData[chapterNo]
  if (!chapterData) return []

  return chapterData.filter((verse) => verse.verseNo >= startVerse && verse.verseNo <= endVerse)
}

// Search transliteration by text
export const searchTransliteration = (searchTerm) => {
  const results = []
  const term = searchTerm.toLowerCase()

  Object.keys(transliterationData).forEach((chapterNo) => {
    const chapter = transliterationData[chapterNo]
    chapter.forEach((verse) => {
      if (verse.translation.toLowerCase().includes(term)) {
        results.push({
          chapterNo: Number.parseInt(chapterNo),
          verseNo: verse.verseNo,
          transliteration: verse.translation,
        })
      }
    })
  })

  return results
}

// Get random verse transliteration
export const getRandomVerseTransliteration = () => {
  const chapters = Object.keys(transliterationData)
  const randomChapter = chapters[Math.floor(Math.random() * chapters.length)]
  const chapterData = transliterationData[randomChapter]
  const randomVerse = chapterData[Math.floor(Math.random() * chapterData.length)]

  return {
    chapterNo: Number.parseInt(randomChapter),
    verseNo: randomVerse.verseNo,
    transliteration: randomVerse.translation,
  }
}
